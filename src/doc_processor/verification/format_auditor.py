"""
Dedicated Format & Quality Auditor for Academic Literature and Textbooks
========================================================================
Performs rigorous multi-dimensional inspection of generated Markdown files:
1. Title integrity and completeness (H1 #, no truncation, no watermark headers)
2. Abstract section extraction (## Abstract, blockquote, metadata hygiene)
3. Heading hierarchy and TOC sanity (IMRAD structure, no over-inflated headings)
4. Table & Figure semantic placement (anchored after first mention, notes isolated)
5. LaTeX math & statistical formula normalization ($...$, balanced delimiters, OCR repairs)
6. References & bibliography formatting (bulleted list, no inline glued citations)
7. Page numbers and running header noise filtering (no orphan page numbers or URLs)
8. Text continuity & paragraph reflow (no broken hyphenations or jarring cuts)

Supports graded disposition:
- Auto-repair for high-confidence syntax/format defects.
- Structured reporting (console, JSON, and Markdown).
- Ollama semantic deep-dive integration for nuanced editorial review.
"""

import json
import logging
import re
from dataclasses import dataclass, field, asdict
from pathlib import Path
from typing import List, Dict, Any, Optional, Tuple

logger = logging.getLogger(__name__)


@dataclass
class AuditIssue:
    severity: str          # "ERROR", "WARNING", "INFO"
    category: str          # "TITLE", "ABSTRACT", "HEADING", "TABLE", "FIGURE", "LATEX", "REFERENCES", "NOISE", "CONTINUITY"
    line_num: Optional[int]
    snippet: str           # Offending text or excerpt
    message: str           # Diagnostic explanation
    suggested_fix: Optional[str] = None
    auto_fixable: bool = False
    confidence: float = 1.0


@dataclass
class AuditReport:
    doc_name: str
    file_path: str
    passed: bool
    total_issues: int
    error_count: int
    warning_count: int
    info_count: int
    score_percent: float
    issues: List[AuditIssue] = field(default_factory=list)
    repaired_count: int = 0
    ollama_review: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "doc_name": self.doc_name,
            "file_path": self.file_path,
            "passed": self.passed,
            "total_issues": self.total_issues,
            "error_count": self.error_count,
            "warning_count": self.warning_count,
            "info_count": self.info_count,
            "score_percent": self.score_percent,
            "repaired_count": self.repaired_count,
            "ollama_review": self.ollama_review,
            "issues": [asdict(i) for i in self.issues],
        }

    def to_markdown(self) -> str:
        status_badge = "✅ **PASSED**" if self.passed else "⚠️ **NEEDS ATTENTION**"
        lines = [
            f"# 📋 文獻排版與格式稽核報告 (Format Audit Report)",
            f"",
            f"- **文獻名稱 (Document)**: `{self.doc_name}`",
            f"- **檔案路徑 (File Path)**: `{self.file_path}`",
            f"- **稽核結果 (Verdict)**: {status_badge}",
            f"- **品質得分 (Score)**: {self.score_percent:.1f}%",
            f"- **瑕疵統計 (Issues)**: ❌ {self.error_count} 嚴重錯誤 | ⚠️ {self.warning_count} 警告 | ℹ️ {self.info_count} 提示 | 🔧 {self.repaired_count} 已自動修復",
            f"",
            f"---",
            f"",
            f"## 一、 瑕疵詳細清單 (Detailed Findings)",
            f"",
        ]

        if not self.issues:
            lines.append("🎉 **完全未發現任何排版或格式瑕疵！文獻格式符合最高品質標準。**\n")
        else:
            lines.append("| 等級 | 類別 | 行號 | 瑕疵說明 | 摘錄片段 | 修正建議 |")
            lines.append("| :--- | :--- | :---: | :--- | :--- | :--- |")
            for iss in self.issues:
                sev_icon = "❌ ERROR" if iss.severity == "ERROR" else ("⚠️ WARN" if iss.severity == "WARNING" else "ℹ️ INFO")
                snip = iss.snippet.replace("\n", " ").replace("|", "\\|")
                if len(snip) > 50:
                    snip = snip[:47] + "..."
                msg = iss.message.replace("\n", " ").replace("|", "\\|")
                fix = (iss.suggested_fix or "人工檢核").replace("\n", " ").replace("|", "\\|")
                if len(fix) > 40:
                    fix = fix[:37] + "..."
                lines.append(f"| {sev_icon} | `{iss.category}` | {iss.line_num or '-'} | {msg} | `{snip}` | {fix} |")
            lines.append("")

        if self.ollama_review:
            lines.extend([
                f"---",
                f"",
                f"## 二、 Ollama 本地大模型深度語義複核評語",
                f"",
                f"```text",
                f"{self.ollama_review.strip()}",
                f"```",
                f"",
            ])

        lines.extend([
            f"---",
            f"*(Generated by doc_processor.verification.format_auditor)*",
        ])
        return "\n".join(lines)


class FormatAuditor:
    """Specialized format and typography auditor for academic literature."""

    def __init__(self, is_literature: bool = True) -> None:
        self.is_literature = is_literature

    def audit_text(
        self,
        md_content: str,
        doc_name: str = "document",
        file_path: str = "",
        ollama_verifier: Optional[Any] = None,
    ) -> AuditReport:
        """Inspects markdown content across all 8 dimensions and returns an AuditReport."""
        issues: List[AuditIssue] = []

        lines = md_content.splitlines()

        # 1. Title Inspection
        self._check_title(md_content, lines, issues)

        # 2. Abstract Inspection
        self._check_abstract(md_content, lines, issues)

        # 3. Heading & TOC Structure
        self._check_headings(md_content, lines, issues)

        # 4. Tables & Figures Placement & Notes
        self._check_tables_and_figures(md_content, lines, issues)

        # 5. LaTeX Math & Statistical Formulas
        self._check_latex_and_stats(md_content, lines, issues)

        # 6. References Section
        self._check_references(md_content, lines, issues)

        # 7. Page Numbers & Running Headers Noise
        self._check_noise_and_page_numbers(md_content, lines, issues)

        # 8. Text Continuity
        self._check_continuity(md_content, lines, issues)

        # Compute summary scores
        error_count = sum(1 for i in issues if i.severity == "ERROR")
        warning_count = sum(1 for i in issues if i.severity == "WARNING")
        info_count = sum(1 for i in issues if i.severity == "INFO")

        # Score calculation: base 100, -15 per error, -3 per warning, -1 per info
        penalty = (error_count * 15) + (warning_count * 3) + (info_count * 1)
        score = max(0.0, min(100.0, 100.0 - penalty))
        passed = (error_count == 0) and (score >= 80.0)

        ollama_review = None
        if ollama_verifier and getattr(ollama_verifier, "is_available", False):
            ai_res = ollama_verifier.audit_structured_format_defects(
                markdown_text=md_content,
                candidate_issues=issues,
                doc_name=doc_name,
            )
            ollama_review = ai_res.get("feedback")

        return AuditReport(
            doc_name=doc_name,
            file_path=file_path,
            passed=passed,
            total_issues=len(issues),
            error_count=error_count,
            warning_count=warning_count,
            info_count=info_count,
            score_percent=score,
            issues=issues,
            ollama_review=ollama_review,
        )

    def audit_file(self, file_path: Path, ollama_verifier: Optional[Any] = None) -> AuditReport:
        """Audits a Markdown file on disk."""
        path = Path(file_path)
        if not path.exists():
            return AuditReport(
                doc_name=path.stem,
                file_path=str(path),
                passed=False,
                total_issues=1,
                error_count=1,
                warning_count=0,
                info_count=0,
                score_percent=0.0,
                issues=[AuditIssue("ERROR", "FILE", None, str(path), "File does not exist")],
            )

        with open(path, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()

        report = self.audit_text(content, doc_name=path.stem, file_path=str(path), ollama_verifier=ollama_verifier)
        return report

    # =========================================================================
    # Dimension Checks
    # =========================================================================

    def _check_title(self, text: str, lines: List[str], issues: List[AuditIssue]) -> None:
        """Verifies presence, completeness, and cleanliness of H1 Title."""
        m_empty = re.search(r'(?m)^#\s*$', text)
        if m_empty:
            line_idx = text[:m_empty.start()].count("\n") + 1
            issues.append(AuditIssue(
                severity="ERROR",
                category="TITLE",
                line_num=line_idx,
                snippet="# ",
                message="論文標題為空字串 (# )",
                suggested_fix="填入完整論文名稱",
            ))
            return

        m_title = re.search(r'(?m)^#\s+([^\n]+)', text)
        if not m_title:
            issues.append(AuditIssue(
                severity="ERROR",
                category="TITLE",
                line_num=1,
                snippet="",
                message="缺少頂級論文標題 (# Title)，文件未以標準 H1 標題起始",
                suggested_fix="在文件開頭補全 # <論文名稱>",
            ))
            return

        title_text = m_title.group(1).strip()
        line_idx = text[:m_title.start()].count("\n") + 1

        # Check for watermark / publisher header masquerading as title
        watermarks = ["NIH Public Access", "Author Manuscript", "ARTICLE IN PRESS", "RESEARCH ARTICLE", "Perspective"]
        for wm in watermarks:
            if title_text.lower() == wm.lower():
                issues.append(AuditIssue(
                    severity="ERROR",
                    category="TITLE",
                    line_num=line_idx,
                    snippet=title_text,
                    message=f"論文標題被誤抓為出版社浮水印/文章類型 ('{wm}')",
                    suggested_fix="過濾該浮水印行，提取其後之真實文章標題",
                ))

        # Check for potential truncation (e.g. title ending with prepositions or colons without continuation)
        truncation_suffixes = (" Evidence from", " A study of", " The effect of", ":", " and", " for", " with")
        if any(title_text.endswith(sfx) for sfx in truncation_suffixes):
            issues.append(AuditIssue(
                severity="WARNING",
                category="TITLE",
                line_num=line_idx,
                snippet=title_text,
                message=f"論文標題疑似跨行截斷 (結尾為 '{title_text.split()[-1]}')",
                suggested_fix="檢查 PDF 首頁，縫合跨行的第二行標題",
            ))

    def _check_abstract(self, text: str, lines: List[str], issues: List[AuditIssue]) -> None:
        """Verifies presence and layout of abstract."""
        if not self.is_literature:
            return

        has_abstract_heading = bool(re.search(r'(?m)^##\s+Abstract\b', text, re.I))
        has_blockquote_abstract = bool(re.search(r'(?m)^>\s+\*\*Abstract\*\*', text, re.I)) or bool(re.search(r'(?m)^>\s+.*?[A-Za-z]{20,}', text))

        if not has_abstract_heading and not has_blockquote_abstract:
            issues.append(AuditIssue(
                severity="ERROR",
                category="ABSTRACT",
                line_num=None,
                snippet="",
                message="未檢測到論文摘要區塊 (缺少 ## Abstract 或 > 引言摘要)",
                suggested_fix="從首頁提取 Abstract 並格式化為 ## Abstract",
            ))
            return

        # Check if abstract contains uncleaned DOI or journal volume strings
        m_abs = re.search(r'(?m)^##\s+Abstract\b\s*\n+([\s\S]*?)(?=(?:^##|\Z))', text, re.I)
        if m_abs:
            abs_body = m_abs.group(1)[:300]
            if re.search(r'\b(?:doi\.org|vol\.\s*\d+|issn)\b', abs_body, re.I):
                issues.append(AuditIssue(
                    severity="WARNING",
                    category="ABSTRACT",
                    line_num=text[:m_abs.start()].count("\n") + 1,
                    snippet=abs_body[:80],
                    message="摘要前置文字夾帶期刊卷期或 DOI 雜訊，未完全清洗",
                    suggested_fix="過濾摘要開頭之出版物元數據行",
                ))

    def _check_headings(self, text: str, lines: List[str], issues: List[AuditIssue]) -> None:
        """Verifies heading structure, IMRAD compliance, and checks for TOC inflation."""
        h2_headings = re.findall(r'(?m)^##\s+([^\n]+)', text)

        # Check for excessive headings (e.g. 28 clinical recommendation numbered headings)
        if len(h2_headings) > 20:
            numbered_headings = [h for h in h2_headings if re.match(r'^\d+\.\s+', h)]
            if len(numbered_headings) > 10:
                issues.append(AuditIssue(
                    severity="WARNING",
                    category="HEADING",
                    line_num=None,
                    snippet=numbered_headings[0],
                    message=f"二級標題 (##) 過多 ({len(h2_headings)} 個)，疑似包含 {len(numbered_headings)} 個清單條目被誤判定為標題",
                    suggested_fix="將以數字開頭且為長句的條目降級為有序清單 (1. ...)",
                ))

        # Check for IMRAD structure in literature papers (> 4 pages)
        if self.is_literature and len(lines) > 200:
            imrad_found = {
                "Introduction": bool(re.search(r'(?m)^##\s+.*?(?:Introduction|Overview|Background)\b', text, re.I)),
                "Methods": bool(re.search(r'(?m)^##\s+.*?(?:Method|Procedure|Model|Approach)\b', text, re.I)),
                "Results/Discussion": bool(re.search(r'(?m)^##\s+.*?(?:Result|Discussion|Findings|Analysis)\b', text, re.I)),
            }
            missing_sections = [k for k, found in imrad_found.items() if not found]
            if len(missing_sections) >= 2:
                issues.append(AuditIssue(
                    severity="INFO",
                    category="HEADING",
                    line_num=None,
                    snippet=", ".join(missing_sections),
                    message=f"論文主體未檢測到部分典型 IMRAD 章節: {', '.join(missing_sections)} (可能為綜述、短通訊或不同命名)",
                    suggested_fix="核對原始 PDF 是否為非典型結構文章",
                ))

    def _check_tables_and_figures(self, text: str, lines: List[str], issues: List[AuditIssue]) -> None:
        """Verifies tables and figures placement, notes isolation, and raw OCR leakage."""
        # 1. Check for unisolated table notes
        unisolated_notes = re.finditer(r'(?m)^(?:(?:\*Note\.\*|Note:|\.Note)\s+([^\n]+))', text)
        for m in unisolated_notes:
            # Check if this note is inside a <table> or <tfoot> or <div class="table-notes">
            start_pos = m.start()
            preceding_window = text[max(0, start_pos - 1500):start_pos]
            inside_tfoot = ("<tfoot" in preceding_window) and ("</tfoot>" not in preceding_window)
            inside_div_notes = ('<div class="table-notes"' in preceding_window) and ("</div>" not in preceding_window)
            if not (inside_tfoot or inside_div_notes):
                line_idx = text[:start_pos].count("\n") + 1
                issues.append(AuditIssue(
                    severity="WARNING",
                    category="TABLE",
                    line_num=line_idx,
                    snippet=m.group(0)[:60],
                    message="表格附註 (Note.) 未被隔離至 <tfoot> 或 table-notes 容器，可能洩漏為孤兒內文",
                    suggested_fix="將附註包覆於 <tfoot><tr class=\"table-notes\"><td colspan=\"...\">...</td></tr></tfoot>",
                ))

        # 2. Check for raw floating OCR numbers around tables (e.g. "Table 1 ... 12 34 56 78")
        raw_ocr_table_leak = re.search(r'(?m)^Table\s+\d+\s*\n+(?:[ \t\d\.\-\—\*]+\n+){3,}', text)
        if raw_ocr_table_leak:
            line_idx = text[:raw_ocr_table_leak.start()].count("\n") + 1
            issues.append(AuditIssue(
                severity="ERROR",
                category="TABLE",
                line_num=line_idx,
                snippet=raw_ocr_table_leak.group(0)[:80],
                message="檢測到未經 HTML 表格化之原始 OCR 數字陣列殘留於內文中",
                suggested_fix="將原始表格數字重構為 <table> 或從表格候選區同步",
            ))

        # 3. Check Figure captions
        img_tags = re.findall(r'!\[([^\]]*)\]\((images/[^)]+)\)', text)
        for caption, img_path in img_tags:
            if not caption.strip():
                issues.append(AuditIssue(
                    severity="INFO",
                    category="FIGURE",
                    line_num=None,
                    snippet=f"![]({img_path})",
                    message=f"圖片缺少說明圖說 (Caption): `{img_path}`",
                    suggested_fix="自 PDF 關聯區域提取 Figure 圖說補齊",
                ))

    def _check_latex_and_stats(self, text: str, lines: List[str], issues: List[AuditIssue]) -> None:
        """Verifies LaTeX syntax, math delimiters, and OCR statistical expression errors."""
        # 1. Check for Elsevier OCR corruption of parentheses e.g. "t ð 24 Þ" or "p o 0: 01"
        corrupted_stats = [
            (r'(?:\*?[tTF]\*?)\s*ð\s*\d+\s*Þ', "統計自由度括號 OCR 破損 (如 't ð 24 Þ')，應轉為 $t(24)$"),
            (r'(?:\*?[pP]\*?)\s*o\s*0?:\s*\d+', "統計顯著性 OCR 破損 (如 'p o 0: 01')，應轉為 $p < 0.01$"),
            (r'(?:\*?[mM]\*?)\s*=\s*\d+:\s*\d+', "平均值冒號 OCR 破損 (如 'M = 4: 46')，應轉為 $M = 4.46$"),
            (r'(?:\*?s\.\s*d\.\*?)\s*=\s*\d+', "標準差未正規化 (如 's. d. =2.02')，應轉為 $SD = 2.02$"),
        ]
        for pat, desc in corrupted_stats:
            m = re.search(pat, text)
            if m:
                line_idx = text[:m.start()].count("\n") + 1
                issues.append(AuditIssue(
                    severity="WARNING",
                    category="LATEX",
                    line_num=line_idx,
                    snippet=m.group(0),
                    message=desc,
                    suggested_fix="呼叫 IMRADResolver._fix_ocr_stats 進行正規化",
                    auto_fixable=True,
                ))

        # 2. Check for unbalanced single dollar signs $
        for idx, line in enumerate(lines, start=1):
            if line.strip().startswith("<!--") or line.strip().startswith("<style"):
                continue
            # Remove escaped \$ and $$ blocks
            line_no_disp = re.sub(r'\$\$.*?\$\$', '', line)
            line_no_esc = line_no_disp.replace(r'\$', '').replace('&#36;', '')
            dollar_count = line_no_esc.count('$')
            if dollar_count % 2 != 0:
                issues.append(AuditIssue(
                    severity="WARNING",
                    category="LATEX",
                    line_num=idx,
                    snippet=line.strip()[:60],
                    message="該行包含未成對閉合的 LaTeX 單字元符號 ($)",
                    suggested_fix="檢查是否為貨幣符號未轉義 (\\$) 或漏閉合",
                ))

        # 3. Check for unescaped currency like "$300"
        currency_match = re.search(r'(?<!\\)\$(?:\d+(?:,\d{3})*(?:\.\d+)?)\b', text)
        if currency_match:
            line_idx = text[:currency_match.start()].count("\n") + 1
            issues.append(AuditIssue(
                severity="WARNING",
                category="LATEX",
                line_num=line_idx,
                snippet=currency_match.group(0),
                message="發現未轉義的貨幣符號，在 KaTeX 下可能被誤判為公式起始符",
                suggested_fix="將 $ 轉義為 \\$ 或 &#36;",
                auto_fixable=True,
            ))

    def _check_references(self, text: str, lines: List[str], issues: List[AuditIssue]) -> None:
        """Verifies References section presence and formatting."""
        if not self.is_literature:
            return

        # Check for inline glued references e.g. "award). **References** Abrahamsson"
        glued = re.search(r'[\.?!]\s+\*\*References\*\*\s+[A-Z]', text)
        if glued:
            line_idx = text[:glued.start()].count("\n") + 1
            issues.append(AuditIssue(
                severity="WARNING",
                category="REFERENCES",
                line_num=line_idx,
                snippet=glued.group(0),
                message="參考文獻標題未獨立換行，粘連於前文句子末尾",
                suggested_fix="將 inline **References** 拆分至新行 ## References",
                auto_fixable=True,
            ))

        has_refs = bool(re.search(r'(?m)^##\s+(?:References|Literature Cited|Bibliography)\b', text, re.I))
        if not has_refs and not glued:
            issues.append(AuditIssue(
                severity="ERROR",
                category="REFERENCES",
                line_num=None,
                snippet="",
                message="未找到標準參考文獻章節 (## References 或 ## Literature Cited)",
                suggested_fix="分離參考文獻並使用 ## References 標題起始",
            ))

    def _check_noise_and_page_numbers(self, text: str, lines: List[str], issues: List[AuditIssue]) -> None:
        """Verifies filtering of running headers, footers, and orphan page numbers."""
        for idx, line in enumerate(lines, start=1):
            s = line.strip()
            # 1. Orphan standalone page numbers
            if re.match(r'^\d{1,4}$', s) and not s.startswith("0"):
                issues.append(AuditIssue(
                    severity="WARNING",
                    category="NOISE",
                    line_num=idx,
                    snippet=s,
                    message=f"檢測到孤立頁碼數字行 (`{s}`) 殘留於正文中",
                    suggested_fix="過濾該孤立頁碼行",
                    auto_fixable=True,
                ))

            # 2. Running headers / URLs leaking into body text
            if s.startswith("cambridge.org/bil") or s.startswith("https://doi.org/10."):
                issues.append(AuditIssue(
                    severity="WARNING",
                    category="NOISE",
                    line_num=idx,
                    snippet=s,
                    message="檢測到頁眉頁腳之期刊網址或 DOI 孤兒行殘留",
                    suggested_fix="過濾該頁眉殘留行",
                    auto_fixable=True,
                ))

    def _check_continuity(self, text: str, lines: List[str], issues: List[AuditIssue]) -> None:
        """Verifies natural paragraph flow across page boundaries."""
        # Check for broken hyphens at end of lines
        broken_hyphens = re.findall(r'[a-zA-Z]+-\s*\n\s*[a-zA-Z]+', text)
        if len(broken_hyphens) > 5:
            issues.append(AuditIssue(
                severity="INFO",
                category="CONTINUITY",
                line_num=None,
                snippet=broken_hyphens[0].replace("\n", " "),
                message=f"文檔中存在 {len(broken_hyphens)} 處跨行連字號未縫合 (Hyphenated line break)",
                suggested_fix="呼叫 stitch_cross_page_continuity 進行縫合",
                auto_fixable=True,
            ))

    # =========================================================================
    # Auto-Repair & Remediation
    # =========================================================================

    def auto_repair(self, text: str) -> Tuple[str, int]:
        """
        Applies safe, deterministic repairs for high-confidence syntax and formatting defects.
        Returns: (repaired_text, repair_count)
        """
        repairs = 0
        new_text = text

        # 1. Fix unescaped currency: "$300" -> "&#36;300"
        def _repl_curr(m):
            nonlocal repairs
            repairs += 1
            return f"&#36;{m.group(1)}"
        new_text, n1 = re.subn(r'(?<!\\)\$(?=(\d+(?:,\d{3})*(?:\.\d+)?\b))', r'\\$', new_text)
        repairs += n1

        # 2. Unglue inline **References**
        def _repl_ref(m):
            nonlocal repairs
            repairs += 1
            return f"{m.group(1)}\n\n## References\n\n{m.group(2)}"
        new_text, n2 = re.subn(r'([\.?!]\s+)\*\*References\*\*\s+([A-Z])', _repl_ref, new_text)

        # 3. Clean orphan standalone page numbers
        lines = new_text.splitlines()
        clean_lines = []
        for line in lines:
            if re.match(r'^\s*\d{1,4}\s*$', line) and len(line.strip()) <= 4:
                repairs += 1
                continue
            clean_lines.append(line)
        new_text = "\n".join(clean_lines)

        return new_text, repairs
